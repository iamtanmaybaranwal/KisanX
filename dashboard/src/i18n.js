export function langMeta(code) {
  return LANGUAGES.find((l) => l.code === code) || LANGUAGES[0];
}

/** tr(key, vars) for a language, with fallback: language -> Hindi (Devanagari langs) -> English. */
export function translator(lang) {
  const own = S[lang] || S.en;
  const mid = HINDI_FALLBACK.has(lang) ? S.hi : {};
  return (key, vars) => {
    let s = own[key] ?? mid[key] ?? S.en[key] ?? key;
    if (vars && typeof s === "string") s = s.replace(/\{(\w)\}/g, (_, k) => (vars[k] ?? ""));
    return s;
  };
}

export function cropName(lang, crop, fallback) {
  const i = CROP_KEYS.indexOf(crop);
  if (i < 0) return fallback || crop;
  const own = (S[lang] || S.en).crops || [];
  const hindi = HINDI_FALLBACK.has(lang) ? S.hi.crops : [];
  return own[i] || hindi[i] || S.en.crops[i] || fallback || crop;     // newer crops: fall back, never blank
}

const fmtH = (h) => (h == null ? "" : h >= 2 ? Math.round(h) : Math.round(h * 10) / 10);

/** Build the decision reason in any language from the Pi's structured decision. */
export function reasonFor(zone, tr, lang) {
  const d = zone.decision;
  if (!d) return "";
  const det = d.details || {};
  const vars = {
    m: zone.moisture == null ? "–" : Math.round(zone.moisture),
    h: fmtH(det.hours_until_min),
    p: det.fc_prob_6h == null ? "" : Math.round(det.fc_prob_6h),
    s: Math.round(d.seconds || 0),
    l: det.liters == null ? "" : Math.round(det.liters * 10) / 10,
    g: Math.round(zone.session?.target_pct ?? det.goal_pct ?? zone.thresholds?.target_pct ?? 0),
  };
  const key = { enough_water: "r_enough_water", ok_12h: "r_ok_12h", ok_for_now: "r_ok_for_now",
    rain_expected: "r_rain_expected", dry: "r_dry", dry_soon: "r_dry_soon", critical_light: "r_critical_light",
    watering: "r_watering", soaking: "r_soaking", no_rise: "r_no_rise", device_offline: "r_device_offline",
    no_sensor: "r_no_sensor" }[d.code];
  if (key) return tr(key, vars);
  return lang === "hi" ? d.reason_hi : d.reason_en;
}
